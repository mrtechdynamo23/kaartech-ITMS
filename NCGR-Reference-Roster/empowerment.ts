// Helper to calculate empowerment summary metrics
export function getEmpowermentStats() {
  const totalPlannedPrograms = academyTrainingPrograms.length;
  const completedPrograms = academyTrainingPrograms.filter(p => p.status === 'Completed').length;
  const inProgressPrograms = academyTrainingPrograms.filter(p => p.status === 'In Progress').length;
  const avgCompletionPct = Math.round(
    academyTrainingPrograms.reduce((s, p) => s + p.completionPct, 0) / totalPlannedPrograms
  );
  const totalParticipants = academyTrainingPrograms.reduce((s, p) => s + p.participants, 0);
  const totalCompletedParticipants = academyTrainingPrograms.reduce((s, p) => s + p.completed, 0);

  const totalKTPlanned = detailedKTList.reduce((s, k) => s + k.sessionsPlanned, 0);
  const totalKTCompleted = detailedKTList.reduce((s, k) => s + k.sessionsCompleted, 0);
  const ktSignedOffCount = detailedKTList.filter(k => k.signoffStatus === 'Approved').length;

  const totalCertificationsEarned = employeeDevelopmentRoster.reduce(
    (s, e) => s + e.certificationsCompleted.length, 0
  );

  return {
    totalPlannedPrograms,
    completedPrograms,
    inProgressPrograms,
    avgCompletionPct,
    totalParticipants,
    totalCompletedParticipants,
    totalKTPlanned,
    totalKTCompleted,
    ktSignedOffCount,
    totalKTRecords: detailedKTList.length,
    totalCertificationsEarned,
    activeDevelopmentCount: employeeDevelopmentRoster.length,
  };
}
