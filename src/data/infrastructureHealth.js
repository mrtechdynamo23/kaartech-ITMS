/**
 * Dynamically computes all Infrastructure Health KPI statistics.
 * Single source of truth helper ensuring all components share identical metrics.
 */
export function getInfraStats(nodes = infraNodes) {
  const total = nodes.length;
  if (total === 0) {
    return {
      total: 0,
      healthy: 0,
      warning: 0,
      critical: 0,
      maintenance: 0,
      avgCpu: 0,
      avgMem: 0,
      avgDisk: 0,
    };
  }

  const healthy = nodes.filter(n => n.status === 'Healthy').length;
  const warning = nodes.filter(n => n.status === 'Warning').length;
  const critical = nodes.filter(n => n.status === 'Critical').length;
  const maintenance = nodes.filter(n => n.status === 'Maintenance').length;
  const avgCpu = Math.round(nodes.reduce((s, n) => s + (n.cpuUtilization || 0), 0) / total);
  const avgMem = Math.round(nodes.reduce((s, n) => s + (n.memoryUtilization || 0), 0) / total);
  const avgDisk = Math.round(nodes.reduce((s, n) => s + (n.diskUtilization || 0), 0) / total);

  return {
    total,
    healthy,
    warning,
    critical,
    maintenance,
    avgCpu,
    avgMem,
    avgDisk,
  };
}
